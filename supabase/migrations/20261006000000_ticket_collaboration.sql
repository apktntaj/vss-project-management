create or replace function public.record_ticket_activity() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    insert into public.ticket_activities (workspace_id, ticket_id, actor_id, kind, change, occurred_at)
    values (new.workspace_id, new.id, new.creator_id, 'CREATED', '{}'::jsonb, new.created_at);
    return new;
  end if;
  if new.title is distinct from old.title or new.description is distinct from old.description or new.priority is distinct from old.priority or new.context_kind is distinct from old.context_kind or new.context_id is distinct from old.context_id then
    insert into public.ticket_activities (workspace_id, ticket_id, actor_id, kind, change)
    values (new.workspace_id, new.id, new.updated_by_id, 'DETAILS_CHANGED', jsonb_build_object('fields', (
      select jsonb_agg(value) from jsonb_array_elements(array_remove(array[
        case when new.title is distinct from old.title then jsonb_build_object('field','TITLE','before',old.title,'after',new.title) end,
        case when new.description is distinct from old.description then jsonb_build_object('field','DESCRIPTION','before',old.description,'after',new.description) end,
        case when new.priority is distinct from old.priority then jsonb_build_object('field','PRIORITY','before',old.priority,'after',new.priority) end,
        case when new.context_kind is distinct from old.context_kind or new.context_id is distinct from old.context_id then jsonb_build_object('field','CONTEXT','before',case when old.context_kind = 'GENERAL' then 'GENERAL' else old.context_kind || ':' || old.context_id end,'after',case when new.context_kind = 'GENERAL' then 'GENERAL' else new.context_kind || ':' || new.context_id end) end
      ], null)) value)));
    new.last_activity_at := now();
  end if;
  if new.assignee_id is distinct from old.assignee_id then
    insert into public.ticket_activities (workspace_id, ticket_id, actor_id, kind, change)
    values (new.workspace_id, new.id, new.updated_by_id, 'ASSIGNEE_CHANGED', jsonb_build_object('before', old.assignee_id, 'after', new.assignee_id));
    new.last_activity_at := now();
  end if;
  if new.status is distinct from old.status then
    insert into public.ticket_activities (workspace_id, ticket_id, actor_id, kind, change)
    values (new.workspace_id, new.id, new.updated_by_id, 'STATUS_CHANGED', jsonb_build_object('before', old.status, 'after', new.status, 'note', coalesce(new.completion_note, null)));
    new.last_activity_at := now();
  end if;
  return new;
end $$;

drop trigger if exists tickets_activity_trigger on public.tickets;
create trigger tickets_activity_trigger before update on public.tickets for each row execute function public.record_ticket_activity();
create trigger tickets_created_activity_trigger after insert on public.tickets for each row execute function public.record_ticket_activity();

create or replace function public.touch_ticket_from_comment() returns trigger language plpgsql as $$
begin
  update public.tickets set last_activity_at = new.created_at where workspace_id = new.workspace_id and id = new.ticket_id;
  return new;
end $$;
drop trigger if exists ticket_comments_touch_ticket on public.ticket_comments;
create trigger ticket_comments_touch_ticket after insert on public.ticket_comments for each row execute function public.touch_ticket_from_comment();

create or replace function public.create_ticket(p_workspace_id uuid, p_actor_id uuid, p_id text, p_title text, p_description text, p_context_kind text, p_context_id text, p_priority text, p_assignee_id uuid) returns public.tickets language plpgsql as $$
declare result public.tickets;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_workspace_id::text || coalesce(p_assignee_id::text, 'unassigned') || 'TODO', 0));
  insert into public.tickets (workspace_id, id, creator_id, assignee_id, context_kind, context_id, title, description, status, sort_order, priority, updated_by_id)
  values (p_workspace_id, p_id, p_actor_id, p_assignee_id, p_context_kind, p_context_id, trim(p_title), nullif(trim(p_description), ''), 'TODO', coalesce((select max(sort_order) + 1 from public.tickets where workspace_id = p_workspace_id and assignee_id is not distinct from p_assignee_id and status = 'TODO'), 1), p_priority, p_actor_id)
  returning * into result;
  return result;
end $$;

create or replace function public.edit_ticket(p_workspace_id uuid, p_actor_id uuid, p_ticket_id text, p_title text, p_description text, p_context_kind text, p_context_id text, p_priority text, p_assignee_id uuid) returns public.tickets language plpgsql as $$
declare result public.tickets;
begin
  update public.tickets set title = trim(p_title), description = nullif(trim(p_description), ''), context_kind = p_context_kind, context_id = p_context_id, priority = p_priority, assignee_id = p_assignee_id, updated_by_id = p_actor_id, updated_at = now() where workspace_id = p_workspace_id and id = p_ticket_id returning * into result;
  if not found then raise exception 'Ticket tidak ditemukan.' using errcode = 'P0002'; end if;
  return result;
end $$;

create or replace function public.assign_ticket(p_workspace_id uuid, p_actor_id uuid, p_ticket_id text, p_assignee_id uuid) returns public.tickets language plpgsql as $$
declare result public.tickets;
begin
  update public.tickets set assignee_id = p_assignee_id, sort_order = coalesce((select max(sort_order) + 1 from public.tickets where workspace_id = p_workspace_id and assignee_id is not distinct from p_assignee_id and status = (select status from public.tickets where workspace_id = p_workspace_id and id = p_ticket_id)), 1), updated_by_id = p_actor_id, updated_at = now() where workspace_id = p_workspace_id and id = p_ticket_id returning * into result;
  if not found then raise exception 'Ticket tidak ditemukan.' using errcode = 'P0002'; end if;
  return result;
end $$;

create or replace function public.move_ticket(p_workspace_id uuid, p_actor_id uuid, p_ticket_id text, p_status text, p_ordered_ticket_ids text[], p_completion_note text, p_reopen_reason text) returns public.tickets language plpgsql as $$
declare result public.tickets;
begin
  update public.tickets set status = p_status, completion_note = case when p_status = 'DONE' then nullif(trim(p_completion_note), '') else null end, completed_at = case when p_status = 'DONE' then now() else null end, updated_by_id = p_actor_id, updated_at = now() where workspace_id = p_workspace_id and id = p_ticket_id returning * into result;
  if not found then raise exception 'Ticket tidak ditemukan.' using errcode = 'P0002'; end if;
  if p_ordered_ticket_ids is not null then
    update public.tickets t set sort_order = ordered.ordinality, updated_at = now()
    from unnest(p_ordered_ticket_ids) with ordinality as ordered(id, ordinality)
    where t.workspace_id = p_workspace_id and t.id = ordered.id;
  end if;
  return result;
end $$;

