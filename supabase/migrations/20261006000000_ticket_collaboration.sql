-- Preserve legacy rows even when the old payload cannot establish attribution.
update public.tickets
set
  context_kind = coalesce(context_kind, case when payload->'context'->>'kind' in ('EVENT', 'JOB') then payload->'context'->>'kind' else 'GENERAL' end),
  context_id = coalesce(context_id, case when payload->'context'->>'kind' in ('EVENT', 'JOB') then nullif(payload->'context'->>'id', '') else null end),
  title = coalesce(title, nullif(trim(payload->>'title'), ''), 'Ticket lama'),
  description = coalesce(description, nullif(trim(payload->>'description'), '')),
  status = coalesce(status, nullif(payload->>'status', ''), 'TODO'),
  sort_order = coalesce(sort_order, nullif(payload->>'order', '')::integer, 1),
  priority = coalesce(priority, nullif(payload->>'priority', ''), 'NORMAL'),
  completion_note = coalesce(completion_note, nullif(payload->'completion'->>'note', '')),
  completed_at = coalesce(completed_at, nullif(payload->'completion'->>'completedAt', '')::timestamptz),
  last_activity_at = coalesce(last_activity_at, updated_at, created_at)
where context_kind is null or title is null or status is null or sort_order is null or priority is null;

update public.tickets t
set assignee_id = u.id
from public.app_users u
where t.assignee_id is null
  and (t.payload->>'assigneeId') = u.id::text;

with numbered as (
  select workspace_id, id, row_number() over (partition by workspace_id order by created_at, id) as number
  from public.tickets
)
update public.tickets t
set ticket_number = numbered.number
from numbered
where t.workspace_id = numbered.workspace_id and t.id = numbered.id;

select setval(pg_get_serial_sequence('public.tickets', 'ticket_number'), coalesce((select max(ticket_number) from public.tickets), 0) + 1, false);

